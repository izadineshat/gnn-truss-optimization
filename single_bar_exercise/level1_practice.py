# سطح ۱: تحلیل تک‌میله و بررسی ایمنی (تنش و کمانش)
# ==============================================================================

# این دو خط باعث می‌شوند متن فارسی در کنسول ویندوز درست چاپ شود (رفع خطای Unicode)
import sys
sys.stdout.reconfigure(encoding="utf-8")

def analyze_bar(P, L, A, E, sigma_yield, is_compression=False):
    """
    این تابع مشخصات یک میله را می‌گیرد و تنش، جابجایی و وضعیت ایمنی آن را بررسی می‌کند.
    
    ورودی‌ها:
    P             : نیروی محوری (نیوتون)
    L             : طول میله (متر)
    A             : سطح مقطع (متر مربع)
    E             : مدول الاستیسیته (پاسکال)
    sigma_yield   : تنش تسلیم یا مجاز ماده (پاسکال)
    is_compression: آیا نیرو فشاری است؟ (True / False)
    """
    
    print("--- شروع تحلیل میله ---")
    
    # ۱. محاسبه تنش محوری (Stress = P / A)
    sigma = P / A  # مقدار به پاسکال (Pa)
    sigma_MPa = sigma / 1e6  # تبدیل به مگاپاسکال (MPa)
    
    # ۲. محاسبه تغییر طول / جابجایی (Delta_L = P * L / (E * A))
    delta_L = (P * L) / (E * A)  # مقدار به متر (m)
    delta_L_mm = delta_L * 1000  # تبدیل به میلی‌متر (mm)
    
    print(f"تنش ایجاد شده: {sigma_MPa:.2f} مگاپاسکال")
    print(f"تغییر طول میله: {delta_L_mm:.4f} میلی‌متر")
    
    # ۳. بررسی ایمنی تنش با دستور شرطی if / else
    if sigma <= sigma_yield:
        print("✅ وضعیت تنش: ایمن (تنش از حد تسلیم کمتر است)")
    else:
        print("❌ وضعیت تنش: خطر تسلیم / گسیختگی! (تنش از حد تسلیم بیشتر است)")
        
    # ۴. اگر نیرو فشاری باشد، بررسی کمانش اولر (Euler Buckling)
    if is_compression:
        import math
        # فرض کنید مقطع دایره‌ای است: I = (A^2) / (4 * pi)
        I = (A ** 2) / (4 * math.pi)
        P_crit = (math.pi ** 2 * E * I) / (L ** 2)
        P_crit_kN = P_crit / 1000
        
        print(f"بار بحرانی کمانش (P_cr): {P_crit_kN:.2f} کیلونیوتون")
        
        if P < P_crit:
            print("✅ وضعیت کمانش: ایمن (نیرو کمتر از بار بحرانی کمانش است)")
        else:
            print("❌ وضعیت کمانش: خطر کمانش! (نیرو از بار بحرانی بیشتر است)")

# ------------------------------------------------------------------------------
# اجرا و تست تابع با مقادیر واقعی (فولاد structural steel)
# ------------------------------------------------------------------------------

# مشخصات ورودی:
P_force = 150000.0      # ۱۵۰ کیلو نیوتون = ۱۵۰,۰۰۰ نیوتون
L_length = 2.0          # ۲ متر
A_area = 0.0008         # ۰.۰۰۰۸ متر مربع (۸ سانتی‌متر مربع)
E_modulus = 200e9       # ۲۰۰ گیگاپاسکال = ۲۰۰,۰۰۰,۰۰۰,۰۰۰ پاسکال (فولاد)
sigma_y = 250e6         # ۲۵۰ مگاپاسکال تنش تسلیم فولاد ST37

print("تست ۱: بررسی میله تحت کشش")
analyze_bar(P=P_force, L=L_length, A=A_area, E=E_modulus, sigma_yield=sigma_y, is_compression=False)

print("\n" + "="*50 + "\n")

print("تست ۲: بررسی میله تحت فشار (بررسی کمانش)")
analyze_bar(P=P_force, L=L_length, A=A_area, E=E_modulus, sigma_yield=sigma_y, is_compression=True)
